"""Stop failure demonstrations from teaching the failure (~/lerobot-env).

Failure episodes are generated by injecting errors into the expert (grasp beside the cube, open the gripper while
lifting / carrying, release off the plate). Behaviour cloning on them would teach exactly those errors. This tool
sets the motion part of the action (dims 0-9) to NaN for the frames of a failure episode *before* the failure is
detected, so only the verdict dims [done, success] are learnt there; the policy's loss ignores NaN entries
(SmolVLADepthPolicy.forward). From the detection on (status [1, 0]: stop and hold still) everything is trained.

    ~/lerobot-env/bin/python -m so101_lang.data.mask_failure_motion --src datasets/lerobot/s512_place9s \
        --dst datasets/lerobot/s512_place9m
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq

from so101_lang.data.skill_subset import vec_stats

MOTION = 10


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", required=True)
    ap.add_argument("--dst", required=True)
    args = ap.parse_args()
    src, dst = Path(args.src), Path(args.dst)
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    for item in src.iterdir():
        if item.name in ("videos", "images"):
            os.symlink(item.resolve(), dst / item.name)
        elif item.name == "meta":
            shutil.copytree(item, dst / "meta")
    actions, masked, n_eps = [], 0, 0
    for f in sorted((src / "data").rglob("*.parquet")):
        t = pq.read_table(f)
        act = np.stack(t.column("action").to_numpy(zero_copy_only=False)).astype(np.float32)
        if act.shape[1] != MOTION + 2:
            raise SystemExit(f"{f}: expected a 12-D action with status dims")
        ep, fr = t.column("episode_index").to_numpy(), t.column("frame_index").to_numpy()
        for e in np.unique(ep):
            rows = np.where(ep == e)[0]
            rows = rows[np.argsort(fr[rows])]
            failed = np.nonzero((act[rows, MOTION] > 0.5) & (act[rows, MOTION + 1] < 0.5))[0]
            if len(failed):
                act[rows[: failed[0]], :MOTION] = np.nan
                masked += int(failed[0])
                n_eps += 1
        actions.append(act)
        i = t.schema.get_field_index("action")
        offsets = pa.array(np.arange(0, act.shape[1] * len(act) + 1, act.shape[1], dtype=np.int32))
        col = pa.ListArray.from_arrays(offsets, pa.array(act.reshape(-1), pa.float32()))  # NaN stays a float NaN, not null
        t = t.set_column(i, t.schema.field(i), col.cast(t.schema.field(i).type))
        out = dst / f.relative_to(src)
        out.parent.mkdir(parents=True, exist_ok=True)
        pq.write_table(t, out)
    stats_path = dst / "meta" / "stats.json"
    stats = json.loads(stats_path.read_text())
    stats["action"] = vec_stats(np.concatenate(actions), stats["action"])
    stats_path.write_text(json.dumps(stats, indent=4))
    total = sum(len(a) for a in actions)
    print(f"[mask] {n_eps} failure episodes, motion masked on {masked}/{total} frames -> {dst}")


if __name__ == "__main__":
    main()
